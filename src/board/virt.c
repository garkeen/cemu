// Reset vector, word-for-word from the QEMU mask ROM dump. The six
// instructions load a0 = mhartid, a1 = fdt address (0x1020), a2 =
// fw_dynamic_info (0x1028) and jump to the firmware entry (0x1018).
static const uint32_t kResetVec[6] = {
    0x00000297,  // auipc t0, 0
    0x02828613,  // addi a2, t0, 40
    0xf1402573,  // csrr a0, mhartid
    0x0202b583,  // ld a1, 32(t0)
    0x0182b283,  // ld t0, 24(t0)
    0x00028067,  // jr t0
};
// fw_dynamic_info fields (opensbi include/sbi/fw_dynamic.h); the values are
// QEMU's no-kernel configuration, measured from the same dump.
static const uint64_t kFwDynInfo[6] = {
    0x4942534f,  // magic FW_DYNAMIC_INFO_MAGIC_VALUE
    2,           // version
    0,           // next_addr: no -kernel payload
    1,           // next_mode: S-mode (FW_DYNAMIC_INFO_NEXT_MODE_S)
    0,           // options
    0,           // boot_hart
};

typedef struct VirtBoard {
  Board base;
  ClintDevice clint;
  PlicDevice plic;
  Uart16550 uart;
  SifiveTestDevice test;
  RamDevice* mrom;
  VirtioBlk* blk;        // slot 0, present only with -dsk
  VirtioConsole* con;    // slot 1, always present
  VirtioInput* kbd;      // slot 2
  VirtioInput* tablet;   // slot 3
  Ramfb32Device fb;      // the DTB framebuffer, straight out of DRAM
  int px, py;            // absolute pointer accumulated from host deltas
} VirtBoard;

// ---- wiring: device lines to CPU interrupt inputs ----

static void OnClintIrq(void* ctx, int line, int level) {
  CpuState* cpu = (CpuState*)ctx;
  cpu->set_irq(cpu, line == kClintLineMsip ? kIrqMsip : kIrqMtip, level);
}

static void OnPlicIrq(void* ctx, int line, int level) {
  CpuState* cpu = (CpuState*)ctx;
  // PLIC context 0 is hart0 M-mode, context 1 is hart0 S-mode (DTB
  // interrupts-extended: M ext then S ext).
  cpu->set_irq(cpu, line == 0 ? kIrqMeip : kIrqSeip, level);
}

static void OnUartIrq(void* ctx, int src, int level) {
  (void)src;
  PlicDeviceIrq((PlicDevice*)ctx, kVirtUartIrq, level);
}

// One virtio slot's line; src is the slot's PLIC source number (slot+1).
static void OnVirtioIrq(void* ctx, int src, int level) {
  PlicDeviceIrq((PlicDevice*)ctx, src, level);
}

static uint64_t ReadTime(void* dev) { return ClintMtime((ClintDevice*)dev); }

// Host window -> virtio keyboard: set-1 make/break to Linux KEY_*.
static void OnHostKey(void* ctx, uint32_t scan, int extended, int up) {
  VirtBoard* vm = (VirtBoard*)ctx;
  const KeyMap* tab = extended ? kKeysExt : kKeys;
  int n = extended ? (int)(sizeof kKeysExt / sizeof kKeysExt[0])
                   : (int)(sizeof kKeys / sizeof kKeys[0]);
  for (int i = 0; i < n; i++) {
    if (tab[i].scan == scan) {
      VirtioInputKey(vm->kbd, tab[i].key, !up);
      return;
    }
  }
}

// Host window -> virtio tablet: deltas accumulated into the 0..0x7fff
// absolute field the device reports (the window itself only produces
// relative motion events).
static void OnHostMouse(void* ctx, int dx, int dy, int dz, int buttons) {
  VirtBoard* vm = (VirtBoard*)ctx;
  vm->px += dx * 0x8000 / kVirtFbWidth;
  vm->py -= dy * 0x8000 / kVirtFbHeight;  // Win32 Y grows downward
  if (vm->px < 0) vm->px = 0;
  if (vm->py < 0) vm->py = 0;
  if (vm->px >= 0x8000) vm->px = 0x7fff;
  if (vm->py >= 0x8000) vm->py = 0x7fff;
  if (dx || dy) VirtioInputPointer(vm->tablet, vm->px, vm->py);
  if (dz) VirtioInputWheel(vm->tablet, dz > 0 ? 1 : -1);
  for (int b = 0; b < 3; b++) {
    int now = (buttons >> b) & 1;
    if (now != ((vm->tablet->buttons >> b) & 1))
      VirtioInputButton(vm->tablet, b, now);
  }
}

// Host input -> the guest's consoles. The firmware talks on the 16550
// (OpenSBI's banner console), the OS on the virtio console (this kernel's
// only serial driver is virtio-console, hvc0); a byte is offered to both --
// whichever has a reader takes it, the other ignores it.
static void OnHostSerial(void* ctx, int ch) {
  VirtBoard* vm = (VirtBoard*)ctx;
  if (DebugOn(kDbgMark)) DebugMark("hostserial", ch, 0);
  Uart16550Receive(&vm->uart, ch);
  if (vm->con) VirtioConsoleReceive(vm->con, ch);
}

static void VirtPoll(Board* m) {
  VirtBoard* vm = (VirtBoard*)m;
  ClintPoll(&vm->clint);
  Uart16550Poll(&vm->uart);
  if (vm->con) VirtioConsolePoll(vm->con);
  VirtioInputPoll(vm->kbd);
  VirtioInputPoll(vm->tablet);
  Ramfb32Poll(&vm->fb);
}

// BoardDestroy frees the Board itself; this hook releases the extra
// allocations only.
static void VirtDestroy(Board* m) {
  VirtBoard* vm = (VirtBoard*)m;
  VirtioBlkDestroy(vm->blk);
  VirtioConsoleDestroy(vm->con);
  VirtioInputDestroy(vm->kbd);
  VirtioInputDestroy(vm->tablet);
  Ramfb32Destroy(&vm->fb);
  RamDestroy(vm->mrom);
}

// ---- FDT ----

static uint32_t Be32(const uint8_t* p) {
  return (uint32_t)p[0] << 24 | (uint32_t)p[1] << 16 | (uint32_t)p[2] << 8 | p[3];
}

static void PutBe64(uint8_t* p, uint64_t v) {
  for (int i = 0; i < 8; i++) p[i] = (uint8_t)(v >> (56 - 8 * i));
}

static void PutBe32(uint8_t* p, uint32_t v) {
  p[0] = (uint8_t)(v >> 24);
  p[1] = (uint8_t)(v >> 16);
  p[2] = (uint8_t)(v >> 8);
  p[3] = (uint8_t)v;
}

// Walks the FDT structure (devicetree specification 0.4, big-endian) and
// rewrites the size cells of the memory node's reg property to the actual
// RAM size, so the tree QEMU generated for 128 MiB describes our DRAM.
static void PatchDtbMemorySize(uint8_t* dtb, uint64_t ram_size) {
  size_t pos = Be32(dtb + 8);  // off_dt_struct
  size_t strings = Be32(dtb + 12);
  int depth = 0;
  int in_memory = 0;
  enum { kFdtBegin = 1, kFdtEndNode = 2, kFdtProp = 3, kFdtNop = 4, kFdtEnd = 9 };
  for (;;) {
    uint32_t tok = Be32(dtb + pos);
    pos += 4;
    if (tok == kFdtBegin) {
      const char* name = (const char*)(dtb + pos);
      size_t nlen = strlen(name);
      if (depth == 1 && strncmp(name, "memory@", 7) == 0) in_memory = 1;
      depth++;
      pos = (pos + nlen + 1 + 3) & ~(size_t)3;
    } else if (tok == kFdtEndNode) {
      depth--;
      if (depth <= 1) in_memory = 0;
    } else if (tok == kFdtProp) {
      uint32_t len = Be32(dtb + pos);
      uint32_t nameoff = Be32(dtb + pos + 4);
      pos += 8;
      const char* nm = (const char*)(dtb + strings + nameoff);
      // reg = <base_hi base_lo size_hi size_lo> under #address-cells=2,
      // #size-cells=2: four 32-bit cells (16 bytes), the size the second
      // 8-byte pair.
      if (in_memory && strcmp(nm, "reg") == 0 && len >= 16) {
        // Cap below the DTB framebuffer: those pages are the scanout
        // (simple-framebuffer binding), not allocatable memory.
        uint64_t usable = kVirtFbBase - kDramBase;
        // reg = <addr(2 cells) size(2 cells)>: the size is value+8
        PutBe64(dtb + pos + 8, ram_size < usable ? ram_size : usable);
      }
      pos = (pos + len + 3) & ~(size_t)3;
    } else if (tok != kFdtNop) {
      break;  // kFdtEnd or corruption: stop
    }
  }
}

// Adds a property to /chosen (devicetree spec 0.4 structure: the property
// token is inserted just before the node's END_NODE, and the name joins the
// strings block at its end, so no existing name offset moves). The blob sits
// in the FDT reserve at the top of DRAM, so growing it in place is safe.
// Returns 0 on success, -1 when /chosen is missing or the property is
// already there.
static int PatchDtbChosenProp(uint8_t* dtb, const char* name, const char* value) {
  size_t pos = Be32(dtb + 8);       // off_dt_struct
  size_t strings = Be32(dtb + 12);  // off_dt_strings
  size_t totalsize = Be32(dtb + 4);
  size_t size_strings = Be32(dtb + 32);
  size_t size_struct = Be32(dtb + 36);
  int depth = 0, in_chosen = 0;
  size_t insert_at = 0;
  int have = 0;
  enum { kFdtBegin = 1, kFdtEndNode = 2, kFdtProp = 3, kFdtNop = 4, kFdtEnd = 9 };
  for (;;) {
    uint32_t tok = Be32(dtb + pos);
    pos += 4;
    if (tok == kFdtBegin) {
      const char* nm = (const char*)(dtb + pos);
      size_t nlen = strlen(nm);
      if (depth == 1 && strcmp(nm, "chosen") == 0) in_chosen = 1;
      depth++;
      pos = (pos + nlen + 1 + 3) & ~(size_t)3;
    } else if (tok == kFdtEndNode) {
      depth--;
      if (in_chosen && depth == 1) insert_at = pos - 4;
      in_chosen = 0;
      if (depth == 0) break;
    } else if (tok == kFdtProp) {
      uint32_t len = Be32(dtb + pos);
      uint32_t nameoff = Be32(dtb + pos + 4);
      if (in_chosen && depth == 2 &&
          strcmp((const char*)(dtb + strings + nameoff), name) == 0)
        have = 1;
      pos += 8;  // len + nameoff; the token itself is consumed above
      pos = (pos + len + 3) & ~(size_t)3;
    } else if (tok != kFdtNop) {
      break;
    }
  }
  if (!insert_at || have) return -1;

  size_t vlen = strlen(value) + 1;
  size_t prop_len = 12 + ((vlen + 3) & ~(size_t)3);
  size_t name_len = strlen(name) + 1;
  // grow in place: strings block moves right by prop_len, the struct tail
  // between the insert point and the strings block by prop_len too, and the
  // new name lands at the strings block's (new) end.
  memmove(dtb + strings + prop_len, dtb + strings, totalsize - strings);
  memmove(dtb + insert_at + prop_len, dtb + insert_at, strings - insert_at);
  uint32_t nameoff = (uint32_t)size_strings;
  PutBe32(dtb + insert_at, kFdtProp);
  PutBe32(dtb + insert_at + 4, (uint32_t)vlen);
  PutBe32(dtb + insert_at + 8, nameoff);
  memcpy(dtb + insert_at + 12, value, vlen);
  memcpy(dtb + strings + prop_len + size_strings, name, name_len);
  PutBe32(dtb + 4, (uint32_t)(totalsize + prop_len + name_len));
  PutBe32(dtb + 12, (uint32_t)(strings + prop_len));
  PutBe32(dtb + 32, (uint32_t)(size_strings + name_len));
  // The property grows the structure block; firmware (OpenSBI's libfdt
  // fdt_open_into) repacks the blob from this field.
  PutBe32(dtb + 36, (uint32_t)(size_struct + prop_len));
  return 0;
}

// ---- creation ----

Board* VirtBoardCreate(const BoardOpts* opts) {
  if (opts->ram_base && opts->ram_base != kDramBase) {
    LogError("virt machine DRAM is fixed at 0x80000000");
    return NULL;
  }
  uint64_t ram_size = opts->ram_size ? opts->ram_size : kDramSizeDefault;
  VirtBoard* vm = (VirtBoard*)calloc(1, sizeof(VirtBoard));
  if (!vm) return NULL;
  Board* m = &vm->base;
  m->name = "virt";

  m->ram = RamCreate(kDramBase, ram_size);
  vm->mrom = RamCreate(kMromBase, kMromSize);
  if (!m->ram || !vm->mrom) {
    RamDestroy(m->ram);
    RamDestroy(vm->mrom);
    free(vm);
    return NULL;
  }
  BusAddRamRegion(&m->bus, kDramBase, ram_size, &kRamOps, m->ram, m->ram->mem);
  BusAddRamRegion(&m->bus, kMromBase, kMromSize, &kRamOps, vm->mrom, vm->mrom->mem);
  m->bin_base = kDramBase;  // firmware loads at the DRAM base

  // Mask-ROM contents: the reset vector, then the data slots it references.
  // start_addr (0x1018) is the firmware load address (m->bin_base, so
  // --bin-base overrides reach the trampoline), fdt_addr (0x1020) is where
  // the DTB will land below, and a2 points at fw_dynamic_info (0x1028).
  uint8_t* mrom = vm->mrom->mem;
  memcpy(mrom, kResetVec, sizeof(kResetVec));
  uint64_t fdt_addr = (kDramBase + ram_size - kFdtReserve) & ~(kFdtReserve - 1);
  uint64_t slots[3 + 6];
  slots[0] = m->bin_base;
  slots[1] = fdt_addr;
  memcpy(slots + 2, kFwDynInfo, sizeof(kFwDynInfo));
  memcpy(mrom + 0x18, slots, sizeof(slots));

  // Place the DTB where the trampoline promises it, with the memory node
  // describing the actual RAM size.
  if (kFdtReserve < kVirtDtbSize || ram_size < kFdtReserve + kVirtDtbSize) {
    LogError("virt machine DRAM too small for the device tree");
    VirtDestroy(m);
    RamDestroy(m->ram);
    free(vm);
    return NULL;
  }
  uint8_t* fdt = m->ram->mem + (fdt_addr - kDramBase);
  memcpy(fdt, kVirtDtb, kVirtDtbSize);
  PatchDtbMemorySize(fdt, ram_size);

  // Devices (QEMU virt DTB): CLINT, PLIC, UART0, sifive test finisher.
  ClintInit(&vm->clint, kTimebaseHz);
  ClintRegister(&m->bus, &vm->clint, kClintBase, kClintSize);
  ClintSetIrqSink(&vm->clint, OnClintIrq, &m->cpu);
  PlicInit(&vm->plic);
  PlicRegister(&m->bus, &vm->plic, kPlicBase, kPlicSize);
  PlicSetIrqSink(&vm->plic, OnPlicIrq, &m->cpu);
  Uart16550Init(&vm->uart);
  BusAddRegion(&m->bus, kUartBase, kUartSize, &kUart16550Ops, &vm->uart);
  Uart16550SetIrqSink(&vm->uart, OnUartIrq, &vm->plic);
  m->serial_in = OnHostSerial;
  m->serial_ctx = vm;
  SifiveTestBind(&vm->test, &m->cpu);
  SifiveTestRegister(&m->bus, &vm->test, kTestBase, kTestSize);

  // Kernel command line: into the tree the trampoline hands the firmware
  // (QEMU's -append delivers it the same way).
  if (opts->append &&
      PatchDtbChosenProp(fdt, "bootargs", opts->append) != 0)
    LogError("virt: /chosen/bootargs not injected (node or property issue)");

  // virtio-mmio slots (DTB /soc/virtio@1000N000, PLIC sources 1..8): slot 0
  // is the disk behind -dsk, slot 1 the console. A slot with no backend
  // stays absent and the guest skips it, exactly like a QEMU virt with no
  // device on that address.
  int occupied[kVirtioSlots] = {0};
  if (opts->dsk) {
    vm->blk = VirtioBlkCreate(&m->bus, kVirtioBase, kVirtioStride, opts->dsk,
                              1, OnVirtioIrq, &vm->plic);
    if (!vm->blk)
      LogError("virt: cannot open disk '%s'", opts->dsk);
    else
      occupied[0] = 1;
  }
  vm->con = VirtioConsoleCreate(&m->bus, kVirtioBase + kVirtioStride, kVirtioStride,
                                2, OnVirtioIrq, &vm->plic);
  occupied[1] = 1;

  // Keyboard and tablet behind the window (-display win32): evdev devices
  // the guest's evdev/X read straight from the virtqueues.
  vm->kbd = VirtioInputCreate(&m->bus, kVirtioBase + 2 * kVirtioStride, kVirtioStride,
                              kVirtioInputKeyboard, 3, OnVirtioIrq, &vm->plic);
  vm->tablet = VirtioInputCreate(&m->bus, kVirtioBase + 3 * kVirtioStride, kVirtioStride,
                                 kVirtioInputTablet, 4, OnVirtioIrq, &vm->plic);
  occupied[2] = 1;
  occupied[3] = 1;
  // The DTB advertises all eight slots, and QEMU's virt machine really does
  // map a transport at every one of them. A slot with no backend must still
  // answer its identity registers, or the driver's probe (which walks the
  // nodes in DTB order, highest address first) takes an access fault before
  // reaching the attached devices.
  for (int i = 0; i < kVirtioSlots; i++)
    if (!occupied[i])
      BusAddRegion(&m->bus, kVirtioBase + (uint64_t)i * kVirtioStride, kVirtioStride,
                   &kVirtioMmioEmptyOps, NULL);
  m->key_in = OnHostKey;
  m->key_ctx = vm;
  m->mouse_in = OnHostMouse;
  m->mouse_ctx = vm;

  // The DTB framebuffer as a display source, when DRAM actually covers it.
  if (ram_size >= kVirtFbBase - kDramBase + kVirtFbStride * kVirtFbHeight) {
    if (Ramfb32Init(&vm->fb, &m->bus, kVirtFbBase, kVirtFbWidth, kVirtFbHeight,
                    kVirtFbStride) != 0) {
      LogError("virt: framebuffer render buffers failed");
    } else {
      m->display_dev = &vm->fb;
      m->display_ops = &kRamfb32DisplayOps;
    }
  }

  m->kernel_base = 0x80200000;  // OpenSBI fw_jump's FW_JUMP_ADDR

  m->cpu.halted = kCpuRunning;
  m->cpu.bus = &m->bus;
  m->cpu.timer_read = ReadTime;
  m->cpu.timer_dev = &vm->clint;
  m->reset_pc = kMromBase;  // reset enters the mask-ROM trampoline
  m->bin_htif = 0;          // virt binaries follow the QEMU boot contract, not HTIF
  m->poll = VirtPoll;
  m->destroy = VirtDestroy;
  return m;
}
